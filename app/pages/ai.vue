        <section id="preamble" class="doc-section">
          <h2 class="doc-section__title">
            <span class="doc-section__num">§0</span>
            Preamble
          </h2>
          <p>
            This document establishes the definitive policy regarding the use of
            Generative Artificial Intelligence (AI) within all creative and technical
            operations. It is designed to safeguard the integrity of human expression,
            ensure legal compliance, and maintain the highest standards of quality
            control in an era of automated content saturation.
          </p>
          <p>
            This policy is binding upon all personnel, including full-time employees,
            part-time staff, freelance contractors, external vendors, and any third
            parties engaged in production workflows. By participating in any capacity
            within our operational ecosystem, all parties implicitly agree to adhere
            to the restrictions and mandates set forth herein.
          </p>
        </section>

        <section id="section-1" class="doc-section">
          <h2 class="doc-section__title">
            <span class="doc-section__num">§1</span>
            Executive Summary &amp; Core Stance
          </h2>

          <div class="doc-subsection">
            <h3 class="doc-subsection__title">
              <span class="doc-subsection__num">1.1</span>
              The &ldquo;Human-First&rdquo; Philosophy
            </h3>
            <p>
              The core operational philosophy is defined as &ldquo;Human-First.&rdquo;
              This stance is not merely a preference but a fundamental requirement for
              the authenticity and quality of our output.
            </p>

            <div class="doc-point">
              <h4 class="doc-point__label">
                <span class="doc-point__letter">A</span>
                Original Creative Vision
              </h4>
              <p>
                Generative AI models function by synthesizing existing data, inherently
                lacking the capacity for genuine intentionality, lived experience, or
                original thought. True artistry requires a human perspective that cannot
                be algorithmically generated. We strictly prioritize the unique nuance,
                emotional resonance, and intentionality that only a human creator can
                provide.
              </p>
            </div>

            <div class="doc-point">
              <h4 class="doc-point__label">
                <span class="doc-point__letter">B</span>
                Higher Quality Control
              </h4>
              <p>
                While generative tools can produce rapid output, they frequently suffer
                from structural inconsistencies, &ldquo;hallucinations,&rdquo; and a
                lack of cohesive narrative logic. The pursuit of excellence demands
                deliberate craftsmanship over automated convenience. Human oversight
                ensures that every element serves a purpose and meets rigorous standards
                of technical and artistic integrity.
              </p>
            </div>

            <div class="doc-point">
              <h4 class="doc-point__label">
                <span class="doc-point__letter">C</span>
                Resistance to Industry Saturation
              </h4>
              <p>
                The market is currently flooded with synthetic media. To distinguish
                authentic work from automated content, we maintain a strict
                zero-tolerance policy regarding generative assets. This ensures that our
                output remains distinct, ethically sourced, and legally defensible.
              </p>
            </div>
          </div>

          <div class="doc-subsection">
            <h3 class="doc-subsection__title">
              <span class="doc-subsection__num">1.2</span>
              Scope &amp; Applicability
            </h3>
            <p>
              This policy applies universally across all operations and media formats,
              including but not limited to:
            </p>
            <ul class="doc-list">
              <li>Visual Arts (Illustration, Graphic Design, Concept Art)</li>
              <li>Motion Media (Video Production, Animation, VFX)</li>
              <li>Audio Media (Music Composition, Sound Design, Voiceover)</li>
              <li>Written Content (Scripts, Narrative Design, Documentation)</li>
              <li>Technical Development (Codebases, Web Architecture)</li>
            </ul>
            <p>
              The restrictions herein apply to all stages of production:
              conceptualization, drafting, final asset creation, and post-production.
            </p>
          </div>
        </section>

        <section id="section-2" class="doc-section">
          <h2 class="doc-section__title">
            <span class="doc-section__num">§2</span>
            Strict Creative Restrictions
          </h2>

          <div class="doc-subsection">
            <h3 class="doc-subsection__title">
              <span class="doc-subsection__num">2.1</span>
              Zero-Tolerance Media Policy
            </h3>
            <p>
              The use of Generative AI to create, assist in creating, or refine any
              creative asset is strictly prohibited. This prohibition applies to final
              assets as well as &ldquo;draft,&rdquo; &ldquo;concept,&rdquo; or
              &ldquo;placeholder&rdquo; materials.
            </p>
            <p>Specifically, the following applications are forbidden:</p>

            <div class="doc-point">
              <h4 class="doc-point__label">
                <span class="doc-point__letter">A</span>
                Illustrations, Artwork, and Graphic Design
              </h4>
              <p>
                The use of AI image generators (e.g., diffusion models, GANs, or similar
                image synthesis tools) is banned. All visual assets must be created
                through manual digital painting, vector illustration, photography, or
                traditional mediums. Sketching, line art, coloring, and texturing must
                be performed by human hands.
              </p>
            </div>

            <div class="doc-point">
              <h4 class="doc-point__label">
                <span class="doc-point__letter">B</span>
                Video Production, Visual Effects, and Animation
              </h4>
              <p>
                The use of AI video generators, frame interpolation tools for the
                creation of new frames, or AI-driven rotoscoping that synthesizes content
                is prohibited. All motion graphics, 3D modeling, rigging, animation, and
                compositing must be executed by human artists. Visual effects must be
                based on real footage or manually created digital assets.
              </p>
            </div>

            <div class="doc-point">
              <h4 class="doc-point__label">
                <span class="doc-point__letter">C</span>
                Music Composition, Audio Tracks, and Voiceovers
              </h4>
              <p>
                The use of AI music generators, AI voice cloning, or synthetic audio
                production is banned. All music must be composed and performed by human
                musicians. All voiceovers must be recorded by human talent. Synthesized
                vocals or algorithmic soundscapes are not permitted in any deliverable.
              </p>
            </div>
          </div>

          <div class="doc-subsection">
            <h3 class="doc-subsection__title">
              <span class="doc-subsection__num">2.2</span>
              Third-Party &amp; Vendor Compliance
            </h3>
            <p>
              All external partners, independent contractors, and freelance contributors
              are legally bound by these prohibitions.
            </p>

            <div class="doc-point">
              <h4 class="doc-point__label">
                <span class="doc-point__letter">A</span>
                Contractual Obligation
              </h4>
              <p>
                All service agreements and statements of work must include a clause
                explicitly forbidding the use of Generative AI in the delivery of
                services. Vendors must warrant that all deliverables are human-made.
              </p>
            </div>

            <div class="doc-point">
              <h4 class="doc-point__label">
                <span class="doc-point__letter">B</span>
                Indemnification
              </h4>
              <p>
                Any vendor found to have utilized Generative AI in violation of this
                policy shall be subject to immediate contract termination and financial
                liability for any legal damages incurred due to copyright infringement or
                intellectual property disputes arising from the use of such tools.
              </p>
            </div>

            <div class="doc-point">
              <h4 class="doc-point__label">
                <span class="doc-point__letter">C</span>
                Verification
              </h4>
              <p>
                We reserve the right to request proof of the creative process (e.g.,
                project files, time-lapse recordings, raw footage) to verify the
                authenticity of vendor deliverables.
              </p>
            </div>
          </div>
        </section>

        <section id="section-3" class="doc-section">
          <h2 class="doc-section__title">
            <span class="doc-section__num">§3</span>
            Approved Technical AI Uses
          </h2>

          <div class="doc-subsection">
            <h3 class="doc-subsection__title">
              <span class="doc-subsection__num">3.1</span>
              Coding &amp; Technical Assistance
            </h3>
            <p>
              The use of AI is permitted solely for non-creative, technical assistance
              where it functions as a productivity tool rather than a creator. Permitted
              uses include:
            </p>

            <div class="doc-point">
              <h4 class="doc-point__label">
                <span class="doc-point__letter">A</span>
                Syntax and Debugging
              </h4>
              <p>
                Utilizing AI-powered code completion tools (e.g., predictive text
                editors) to suggest syntax, identify logical errors, or explain standard
                library functions.
              </p>
            </div>

            <div class="doc-point">
              <h4 class="doc-point__label">
                <span class="doc-point__letter">B</span>
                Script Automation
              </h4>
              <p>
                Generating small scripts for build processes, file management, or data
                parsing. This excludes the generation of core product architecture or
                proprietary algorithms.
              </p>
            </div>

            <div class="doc-point">
              <h4 class="doc-point__label">
                <span class="doc-point__letter">C</span>
                Documentation
              </h4>
              <p>
                Assisting in the formatting or grammatical correction of technical
                documentation, provided that the technical content and logic are
                human-derived.
              </p>
            </div>

            <div class="doc-point">
              <h4 class="doc-point__label">
                <span class="doc-point__letter">D</span>
                Learning &amp; Research
              </h4>
              <p>
                Using AI chatbots to explain technical concepts, research generic
                solutions to common problems, or summarize public documentation.
              </p>
            </div>
          </div>

          <div class="doc-subsection">
            <h3 class="doc-subsection__title">
              <span class="doc-subsection__num">3.2</span>
              Data Security &amp; Privacy
            </h3>
            <p>
              Strict rules govern the input of data into AI models to prevent security
              breaches and intellectual property leakage.
            </p>

            <div class="doc-point">
              <h4 class="doc-point__label">
                <span class="doc-point__letter">A</span>
                Prohibition on Proprietary Data
              </h4>
              <p>
                Under no circumstances shall proprietary code, sensitive user data,
                personal identifiable information (PII), trade secrets, or internal
                strategic documents be uploaded to public AI models or unvetted
                third-party services.
              </p>
            </div>

            <div class="doc-point">
              <h4 class="doc-point__label">
                <span class="doc-point__letter">B</span>
                Vetted Enterprise Solutions
              </h4>
              <p>
                Only AI tools hosted on private, secure servers with strict data retention
                policies (i.e., &ldquo;no-training&rdquo; guarantees) may be used for
                technical tasks. Public, consumer-grade AI interfaces are strictly
                prohibited for any work-related technical tasks.
              </p>
            </div>

            <div class="doc-point">
              <h4 class="doc-point__label">
                <span class="doc-point__letter">C</span>
                Audit Trail
              </h4>
              <p>
                Developers must maintain a log of AI-assisted technical tasks. This log
                must specify the tool used and the nature of the assistance provided
                (e.g., &ldquo;Syntax correction on line 40&rdquo;).
              </p>
            </div>
          </div>
        </section>

        <section id="section-4" class="doc-section">
          <h2 class="doc-section__title">
            <span class="doc-section__num">§4</span>
            Transparency, Accountability &amp; Safeguards
          </h2>

          <div class="doc-subsection">
            <h3 class="doc-subsection__title">
              <span class="doc-subsection__num">4.1</span>
              Disclosure &amp; Proof of Authenticity
            </h3>
            <p>
              To maintain trust with clients and the audience, a policy of transparency
              is enforced.
            </p>

            <div class="doc-point">
              <h4 class="doc-point__label">
                <span class="doc-point__letter">A</span>
                Public Declaration
              </h4>
              <p>
                All releases shall include a statement affirming that the work is 100%
                human-made. This declaration serves as a mark of quality and ethical
                production.
              </p>
            </div>

            <div class="doc-point">
              <h4 class="doc-point__label">
                <span class="doc-point__letter">B</span>
                Audit Trails
              </h4>
              <p>For every project, a comprehensive audit trail must be maintained. This includes:</p>
              <ul class="doc-list">
                <li>Raw project files (e.g., .PSD, .AI, .BLEND, .WAV)</li>
                <li>Version history showing progressive changes</li>
                <li>Source footage and raw audio recordings</li>
                <li>Notes and sketches from the conceptual phase</li>
              </ul>
            </div>

            <div class="doc-point">
              <h4 class="doc-point__label">
                <span class="doc-point__letter">C</span>
                Asset Rejection
              </h4>
              <p>
                Any asset suspected of being AI-generated will be immediately rejected.
                The burden of proof lies with the creator to demonstrate the human origin
                of the asset. Failure to provide adequate proof of the creative process
                will result in the rejection of the deliverable.
              </p>
            </div>
          </div>

          <div class="doc-subsection">
            <h3 class="doc-subsection__title">
              <span class="doc-subsection__num">4.2</span>
              Internal Oversight &amp; Enforcement
            </h3>
            <p>
              Compliance with this policy is mandatory. Violations will be met with swift
              and decisive action.
            </p>

            <div class="doc-point">
              <h4 class="doc-point__label">
                <span class="doc-point__letter">A</span>
                Regular Audits
              </h4>
              <p>
                Internal audits will be conducted periodically to ensure adherence to
                this policy. These audits will review project files, technical logs, and
                vendor contracts.
              </p>
            </div>

            <div class="doc-point">
              <h4 class="doc-point__label">
                <span class="doc-point__letter">B</span>
                Consequences for Violations
              </h4>
              <p>
                Violations of this policy will result in disciplinary action, up to and
                including:
              </p>
              <ul class="doc-list">
                <li>Immediate termination of employment or contract.</li>
                <li>Forfeiture of payment for the offending work.</li>
                <li>
                  Legal action for breach of contract and potential copyright
                  infringement.
                </li>
                <li>
                  Blacklisting of the vendor or contractor from future projects.
                </li>
              </ul>
            </div>

            <div class="doc-point">
              <h4 class="doc-point__label">
                <span class="doc-point__letter">C</span>
                Reporting Mechanism
              </h4>
              <p>
                Any team member or contractor who becomes aware of a violation of this
                policy is obligated to report it immediately to the designated compliance
                officer.
              </p>
            </div>
          </div>
        </section>

        <section id="section-5" class="doc-section">
          <h2 class="doc-section__title">
            <span class="doc-section__num">§5</span>
            Conclusion
          </h2>
          <p>
            This policy exists to protect the integrity of the craft and the rights of
            human creators. By adhering to these restrictions, all contributors ensure
            that the work produced remains authentic, legally secure, and distinctly
            human.
          </p>
